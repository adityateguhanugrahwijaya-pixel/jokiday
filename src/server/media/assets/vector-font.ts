export interface VectorTextResult {
  svg: string;
  width: number;
}

export function renderVectorText(text: string, fontSize: number): VectorTextResult {
  const scale = fontSize / UNITS_PER_EM;
  let cursorX = 0;
  const paths: string[] = [];

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const glyph = GLYPH_MAP[char] || GLYPH_MAP["?"] || { d: "", adv: 500 };
    if (glyph.d) {
      paths.push(`<path d="${glyph.d}" transform="translate(${cursorX}, 0)" />`);
    }
    cursorX += glyph.adv;
  }

  const width = Math.round(cursorX * scale);
  const svg = `<g transform="scale(${scale})">${paths.join("")}</g>`;

  return { svg, width };
}
